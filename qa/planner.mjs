// node qa/planner.mjs [url] [out] – Test-Termin eintragen, Countdown/Vorbereitung, Heute üben, Probetest
import { open } from './lib.mjs';
const url = process.argv[2] ?? 'http://localhost:5192/';
const out = process.argv[3] ?? 'qa/shots/planner';
const { p, shot, click, done } = await open({ url, out, grade: 3 });
let fails = 0;
const ok = (c, w) => { console.log(`${c ? '✓' : '✗'} ${w}`); if (!c) fails++; };
await click('Tests');
await p.getByRole('tab', { name: /Termine/ }).click();
await shot('termine-leer');
await click('Test-Termin eintragen');
await p.getByLabel(/Schriftliche Addition/).check();
await p.getByLabel(/Schriftliche Subtraktion/).check();
await p.fill('#pnote', 'Kapitel 3');
await shot('formular', true);
await click('Termin speichern');
await shot('termin');
ok(await p.getByText(/Mathe-Test in 7 Tagen/).isVisible(), 'Countdown „in 7 Tagen“');
await click('Lernen');
ok(await p.getByText(/Mathe-Test in 7 Tagen/).isVisible(), 'Termin-Karte auf der Startseite');
await shot('home');
await click('Heute üben');
ok(await p.locator('.prompt').first().isVisible(), 'Üben startet');
await p.getByRole('button', { name: 'Übung beenden' }).click();
const y = p.getByRole('button', { name: 'Ja, beenden' });
if (await y.isVisible({ timeout: 800 }).catch(() => false)) await y.click();
await click('Probetest');
ok(await p.locator('.timer').isVisible(), 'Probetest startet mit Zeit');
await shot('probetest');
process.exit((await done()) + fails);
