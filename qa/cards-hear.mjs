// node qa/cards-hear.mjs [url] – Vokabelkarten „👂 Nur hören“: vorne kein Wort und kein Bild, nach dem Umdrehen beides
import { open } from './lib.mjs';
const url = process.argv[2] ?? 'http://localhost:5192/';
const { p, shot, click, done } = await open({ url, out: 'qa/shots/cards-hear', grade: 4 });
let bad = 0;
const check = (ok, msg) => { console.log(`${ok ? '✓' : '✗'} ${msg}`); if (!ok) bad++; };
await click('Englisch');
await click('Vokabeln lernen');
const sheet = p.locator('.sheet');
await sheet.getByRole('radio', { name: /Karteikarten/ }).click();
await sheet.getByRole('button', { name: 'Keins' }).click();
await sheet.locator('label.list-row', { hasText: 'Animals – Tiere' }).locator('input[type=checkbox]').check();
await sheet.getByRole('radio', { name: /Nur hören/ }).click();
await sheet.getByRole('button', { name: /Los geht/ }).click();
await p.locator('.vcard').waitFor({ timeout: 8000 });
await shot('vorne');
const frontWord = (await p.locator('.vcard-word').innerText()).trim();
check(frontWord === '👂', `vorne nur das Ohr (${frontWord})`);
check(!(await p.locator('.vcard .vcard-vis').count()), 'vorne kein Bild');
check(await p.getByRole('button', { name: 'Nochmal anhören' }).isVisible(), 'Knopf „Nochmal anhören“');
await p.getByRole('button', { name: 'Umdrehen', exact: true }).click();
await p.waitForTimeout(150);
await shot('hinten');
const word = (await p.locator('.vcard-word').innerText()).trim();
const back = (await p.locator('.vcard-back').innerText()).trim();
check(/^[a-z]/i.test(word) && word !== '👂' && back.length > 1, `hinten Englisch und Deutsch: ${word} – ${back}`);
check(!!(await p.locator('.vcard .vcard-vis').count()), 'hinten mit Bild');
await p.getByRole('button', { name: /Gewusst/ }).click();
await p.waitForTimeout(150);
check((await p.locator('.vcard-word').innerText()).trim() === '👂', 'nächste Karte wieder nur zum Hören');
process.exit((await done()) + bad);
